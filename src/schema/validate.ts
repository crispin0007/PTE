import type { z } from 'zod';
import { QUESTION_SCHEMAS, isQuestionType, wordCount, type Question } from './questions.ts';
import { Registry, type ItemTypeDef } from './registry.ts';

export type SourceFile = {
  /** Path relative to the repo root, using forward slashes, e.g. content/questions/reading/<type>/<id>.yaml */
  path: string;
  data: unknown;
};

export type AssetLookup = {
  /** Whether content-assets/<path> exists. */
  exists(path: string): boolean;
  /** Whether content-assets/<path minus extension>.meta.yaml exists. */
  hasSidecar(path: string): boolean;
};

export type ValidationResult = {
  errors: string[];
  warnings: string[];
  registry: ItemTypeDef[];
  questions: { path: string; question: Question }[];
};

function formatIssues(file: string, error: z.ZodError): string[] {
  return error.issues.map((i) => `${file}: ${i.path.length ? i.path.join('.') + ': ' : ''}${i.message}`);
}

function sentenceCount(text: string): number {
  return (text.trim().match(/[.!?](\s|$)/g) ?? []).length;
}

/**
 * Validates the whole question bank. Pure: file reading is done by the caller, so the same rules
 * run in CI (scripts/validate-content.ts), in the Vite build and in unit tests.
 */
export function validateBank(
  registryData: unknown,
  files: SourceFile[],
  assets: AssetLookup,
): ValidationResult {
  const errors: string[] = [];
  const warnings: string[] = [];
  const questions: ValidationResult['questions'] = [];

  const reg = Registry.safeParse(registryData);
  if (!reg.success) {
    return { errors: formatIssues('content/item-types.yaml', reg.error), warnings, registry: [], questions };
  }
  const registry = reg.data;
  const byId = new Map(registry.map((d) => [d.id, d]));
  for (const d of registry) {
    if (!isQuestionType(d.id)) errors.push(`content/item-types.yaml: type ${d.id} has no schema in src/schema/questions.ts`);
  }

  const seen = new Map<string, string>();
  const counts = new Map<string, number>();

  for (const file of files) {
    const data = file.data as { type?: unknown } | null;
    const type = data?.type;
    if (!isQuestionType(type) || !byId.has(type)) {
      errors.push(`${file.path}: unknown type ${JSON.stringify(type)}`);
      continue;
    }
    const parsed = QUESTION_SCHEMAS[type].safeParse(data);
    if (!parsed.success) {
      errors.push(...formatIssues(file.path, parsed.error));
      continue;
    }
    const q = parsed.data as Question;
    const def = byId.get(type)!;
    const fileErrors: string[] = [];
    const err = (msg: string) => fileErrors.push(`${file.path}: ${msg}`);

    const parts = file.path.split('/');
    const stem = parts.at(-1)!.replace(/\.ya?ml$/, '');
    if (q.id !== stem) err(`id ${q.id} does not match the file name ${stem}`);
    if (!q.id.startsWith(type.replaceAll('_', '-') + '-')) err(`id must start with ${type.replaceAll('_', '-')}-`);
    if (parts.at(-2) !== type || parts.at(-3) !== def.skill) {
      err(`file must be in content/questions/${def.skill}/${type}/`);
    }
    const other = seen.get(q.id);
    if (other) err(`duplicate id, also used by ${other}`);
    seen.set(q.id, file.path);

    if ('sample_answer' in q && def.word_limits) {
      const n = wordCount(q.sample_answer);
      const { min, max } = def.word_limits;
      if (n < min || n > max) err(`sample_answer has ${n} words, outside the ${min}-${max} limit`);
    }
    if (q.type === 'writing_summarize_written_text' && sentenceCount(q.sample_answer) !== 1) {
      err('sample_answer for Summarize Written Text must be exactly one sentence');
    }

    for (const field of ['audio', 'image'] as const) {
      const asset = (q as Record<string, unknown>)[field];
      if (typeof asset !== 'string') continue;
      if (!assets.exists(asset)) {
        // Audio is generated by TTS after writing, so it is only required once a question ships.
        if (field === 'audio' && q.status !== 'published') warnings.push(`${file.path}: audio not generated yet (${asset})`);
        else err(`missing asset content-assets/${asset}`);
      } else if (!assets.hasSidecar(asset)) {
        err(`asset content-assets/${asset} has no .meta.yaml sidecar`);
      }
    }

    errors.push(...fileErrors);
    if (!fileErrors.length) questions.push({ path: file.path, question: q });
    counts.set(type, (counts.get(type) ?? 0) + 1);
  }

  for (const d of registry) {
    if (d.enabled && !counts.get(d.id)) warnings.push(`content/item-types.yaml: enabled type ${d.id} has no questions`);
  }

  return { errors, warnings, registry, questions };
}
